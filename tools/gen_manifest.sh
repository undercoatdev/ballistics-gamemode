#!/bin/sh
# Regenerates gamemode/core/sh_manifest.lua: the list of module Lua files.
# Remote clients load from the downloaded Lua pack, where file.Find can come
# back empty; the loader falls back to this list. Run after adding a file.
cd "$(dirname "$0")/../gamemodes/ballistics/gamemode" || exit 2
{
	echo "-- Generated by tools/gen_manifest.sh. Do not edit by hand."
	echo "BALLISTICS = BALLISTICS or {}"
	echo "BALLISTICS.Manifest = {"
	echo "	core = {"
	for f in $(cd core && ls *.lua | sort); do [ "$f" = sh_manifest.lua ] || echo "		\"$f\","; done
	echo "	},"
	echo "	modules = {"
	for f in $(find modules -name '*.lua' | sort); do echo "		\"$f\","; done
	echo "	},"
	echo "}"
} > core/sh_manifest.lua
